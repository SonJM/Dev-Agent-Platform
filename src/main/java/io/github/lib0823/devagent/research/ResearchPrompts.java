package io.github.lib0823.devagent.research;

/** 질의 결과 2차 검증(독립 검증자 → 지적 반영)·이슈 초안 형식용 프롬프트. */
final class ResearchPrompts {

    private ResearchPrompts() {
    }

    static String verifierSystem() {
        return "당신은 조사 문서의 사실 검증자입니다. 작성자와 다른 독립 세션이며, 문서를 믿지 말고 저장소 소스에서 직접 확인합니다. "
                + "이 세션은 읽기 전용입니다: 파일을 수정·생성하지 말고 빌드·테스트도 돌리지 마세요. "
                + "한국어로 쓰되 코드 식별자·파일명은 원문 그대로.";
    }

    /**
     * 검증자 프롬프트. 수치는 반드시 다시 세고, 목록은 누락·과잉을, 근거 경로는 실제 존재와 내용 일치를 표본 확인하게 한다.
     * 출력 형식은 이슈 리뷰어와 같은 "## 판정" 규약(VerifyService.parseVerdict 재사용).
     */
    static String verifierPrompt(String question, String document) {
        return "아래는 다른 세션이 이 저장소를 조사해 쓴 문서입니다. 질문에 대한 답으로서 사실이 맞는지 검증하세요.\n\n"
                + "검증 방법\n"
                + "1. 문서의 수치(개수·합계)는 직접 다시 셉니다(Grep 결과 수 등). 문서의 숫자를 그대로 믿지 마세요.\n"
                + "2. 목록·표는 누락된 항목과 잘못 들어간 항목이 없는지 독립적으로 찾아 비교합니다.\n"
                + "3. 근거로 든 파일 경로·줄번호·식별자 가운데 최소 5개(문서가 짧으면 전부)를 열어 실제와 일치하는지 봅니다.\n"
                + "4. '추정'·'미확인'이라고 밝힌 부분은 문제 삼지 않습니다. 단정한 내용이 틀렸을 때만 문제입니다.\n"
                + "5. 표현·형식·문체는 평가하지 않습니다. 사실 오류와 질문에 답하지 못한 부분만 봅니다.\n\n"
                + "다음 형식으로만 출력하세요.\n"
                + "## 판정\nPASS 또는 FAIL (한 단어. 사실 오류나 중요한 누락이 하나라도 있으면 FAIL)\n"
                + "## 확인한 항목\n(표: 주장 | 확인 방법 | 결과(일치/불일치))\n"
                + "## 문제\n(FAIL 일 때만: 무엇이 틀렸고 올바른 값·근거가 무엇인지 항목별로. PASS 면 '없음')\n\n"
                + "--- 질문 ---\n" + question + "\n\n--- 검증할 문서 ---\n" + document;
    }

    /**
     * 결과 형식이 "이슈 초안"일 때의 요청. 조사는 평소처럼 하되 출력만 GitHub 이슈 본문 틀로 바꾼다(시스템 프롬프트의 문서 틀보다 우선).
     * 첫 줄 {@code # 제목} 이 이슈 제목이 되고 나머지가 본문이 된다(화면 「이슈로 등록」). 이 이슈는 이슈 에이전트가 읽고 수정하므로
     * 원인·수정 방향에 파일 근거를 남기게 한다.
     */
    static String issueDraftPrompt(String question, boolean resume) {
        return (resume ? "앞선 조사에 이어지는 요청입니다. 이미 읽은 내용을 활용하되 부족한 부분은 소스에서 다시 확인한 뒤, "
                : "다음 요청에 대해 프로젝트 소스를 조사한 뒤, ")
                + "결과를 GitHub 이슈 초안으로 작성해 주세요. 이 이슈는 다른 개발자(또는 수정 에이전트)가 읽고 바로 작업할 수 있어야 합니다.\n\n"
                + "이번 출력은 시스템 프롬프트의 문서 형식 대신 아래 형식만 따릅니다. 초안 앞뒤에 인사·설명 문장을 붙이지 마세요.\n"
                + "# <이슈 제목 — 한 줄, 80자 이내, 무엇을 어떻게 할지 드러나게>\n"
                + "## 배경\n(왜 필요한지 2~4줄)\n"
                + "## 현재 동작\n(지금 어떻게 되어 있는지. 근거 파일 경로:라인)\n"
                + "## 요구 사항\n(바뀌어야 할 동작을 항목으로. 검증 가능한 문장으로)\n"
                + "## 수정 방향\n(손댈 파일·함수와 방법. 소스에서 확인한 것만, 추측은 '추정' 표시)\n"
                + "## 확인 방법\n(수정 뒤 무엇을 보면 되는지: 화면 경로, 테스트, 명령)\n"
                + "## 참고\n(관련 파일, 주의할 영향 범위. 없으면 '없음')\n\n"
                + "요청이 하나의 이슈로 묶기 어려울 만큼 넓으면 가장 핵심인 한 건으로 쓰고, 나머지는 '## 참고' 에 별도 이슈 후보로 적으세요.\n\n"
                + "--- 요청 ---\n" + question;
    }

    /** 이슈 초안에 대한 검증 지적 반영 요청. 이슈 본문에 검증 메모가 섞이지 않게 한다. */
    static String reviseIssuePrompt(String problems) {
        return "독립 검증자가 방금 이슈 초안에서 아래 문제를 지적했습니다. 각 지적을 소스에서 직접 다시 확인하세요(검증자가 틀렸을 수도 있습니다). "
                + "맞는 지적은 반영하고, 틀린 지적은 반영하지 않습니다. 그런 다음 같은 이슈 형식(# 제목 / ## 배경 / ## 현재 동작 / ## 요구 사항 / "
                + "## 수정 방향 / ## 확인 방법 / ## 참고)으로 초안 전체를 다시 출력하세요. 검증 과정에 대한 언급이나 앞뒤 설명 문장은 넣지 마세요.\n\n"
                + "--- 검증자 지적 ---\n" + problems;
    }

    /** 작성 세션에 돌려보내는 수정 요청. 지적을 다시 확인하게 하고(검증자도 틀릴 수 있다) 문서 전체를 다시 내게 한다. */
    static String revisePrompt(String problems) {
        return "독립 검증자가 방금 문서에서 아래 문제를 지적했습니다. 각 지적을 소스에서 직접 다시 확인하세요(검증자가 틀렸을 수도 있습니다). "
                + "맞는 지적은 반영하고, 틀린 지적은 반영하지 않습니다. 그런 다음 같은 형식으로 문서 전체를 다시 출력하세요. "
                + "'## 미확인·주의' 절 끝에 '검증 반영:' 으로 시작하는 줄을 넣어 무엇을 고쳤고 무엇을 반영하지 않았는지(이유) 한두 줄로 적으세요.\n\n"
                + "--- 검증자 지적 ---\n" + problems;
    }
}
